"""Assembles a PR title + markdown body from the TaskPlan.

Every number and pass/fail result in the body is templated in directly from
the structured AgentReports -- the LLM is never asked to restate a cost
figure or a scan result from memory, since that's exactly the kind of thing
a model can subtly get wrong. The LLM's only job (if Ollama is reachable) is
a short, constrained "why" paragraph in plain English; a templated sentence
is used instead if it isn't.
"""
from __future__ import annotations

from backend.llm import ollama_client
from backend.orchestrator.state import TaskPlan


def _resource_name(resource) -> str:
    """CloudResource may arrive as the plain string value (pydantic's
    use_enum_values coerces it) or as the Enum member itself, depending on
    how the ServiceSpec was constructed -- normalize either way instead of
    relying on str(), which prints "CloudResource.S3_BUCKET" for enum
    members rather than "s3_bucket"."""
    return resource.value if hasattr(resource, "value") else str(resource)


def _first_line(text: str) -> str:
    return text.strip().splitlines()[0] if text and text.strip() else "no output"


def _summarize_validations(plan: TaskPlan) -> str:
    lines = []
    for v in plan.all_validations():
        if not v.ran:
            lines.append(f"- ⚠️ **{v.tool}**: skipped ({_first_line(v.output)})")
        elif v.ok:
            lines.append(f"- ✅ **{v.tool}**: passed")
        else:
            lines.append(f"- ❌ **{v.tool}**: found issues -- see CI logs for details")
    return "\n".join(lines) if lines else "_No validations ran._"


def _cost_summary(plan: TaskPlan) -> str:
    total = plan.total_monthly_cost_usd()
    if total is not None:
        return f"**Estimated additional cost: ${total:.2f}/month** (via Infracost)"
    estimates = plan.all_cost_estimates()
    if estimates and not estimates[0].ran:
        return "_Cost estimate skipped (infracost not installed)._"
    return "_Cost estimate unavailable -- see infracost output in CI logs._"


def _files_summary(plan: TaskPlan) -> str:
    lines = [f"- `{f.path}`" for f in plan.all_files()]
    return "\n".join(lines) if lines else "_No files generated._"


def _heuristic_explanation(plan: TaskPlan) -> str:
    spec = plan.spec
    resources = f", provisioning {', '.join(_resource_name(r) for r in spec.cloud_resources)}" if spec.cloud_resources else ""
    visibility = "publicly" if spec.public_endpoint else "internally"
    return (
        f"Adds the '{spec.service_name}' service running {spec.replicas} replica(s) of "
        f"`{spec.container_image}`, exposed {visibility} on port {spec.container_port}{resources}. "
        f'Generated from the request: "{plan.request_text}".'
    )


def _explain(plan: TaskPlan) -> str:
    spec = plan.spec
    if ollama_client.is_available():
        resource_list = ", ".join(_resource_name(r) for r in spec.cloud_resources) if spec.cloud_resources else "no additional cloud resources"
        prompt = (
            f'A developer requested: "{plan.request_text}"\n\n'
            f"This was translated into a service named '{spec.service_name}' "
            f"({spec.replicas} replicas of {spec.container_image}, "
            f"{'publicly' if spec.public_endpoint else 'internally'} exposed on port {spec.container_port}, "
            f"with {resource_list}).\n\n"
            "Write a 2-3 sentence plain-English explanation of this change for a pull request "
            "description, aimed at a human reviewer. Do not invent any facts, numbers, or resources "
            "beyond what is stated above. Do not use markdown headers."
        )
        try:
            text = ollama_client.generate(prompt, temperature=0.3).strip()
            if text:
                return text
        except ollama_client.OllamaUnavailable:
            pass
    return _heuristic_explanation(plan)


def build_pr_title(plan: TaskPlan) -> str:
    return f"Add {plan.spec.service_name} service (AI-generated)"


def build_pr_body(plan: TaskPlan) -> str:
    return f"""## Summary

{_explain(plan)}

## Files changed

{_files_summary(plan)}

## Validation results

{_summarize_validations(plan)}

## Cost impact

{_cost_summary(plan)}

## Rollback plan

This change has not been deployed yet. Once merged, Jenkins builds it and ArgoCD syncs it to the
cluster. If the rollout fails, the Observability Agent will recommend -- but will not perform -- a
rollback, with evidence attached, and will wait for explicit human approval before anything is rolled
back.

---
*Generated by ai-platform-engineer from the request: "{plan.request_text}"*
"""


def run(plan: TaskPlan) -> TaskPlan:
    """Fills in plan.pr_title / plan.pr_body in place and returns the plan."""
    plan.pr_title = build_pr_title(plan)
    plan.pr_body = build_pr_body(plan)
    return plan
